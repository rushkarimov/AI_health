# Подмена на версии из Langfuse.
#
# Вместо правки 26 обращений вида prompts.PHOTO_USER по семи файлам —
# перехват на уровне модуля: __getattr__ вызывается, когда атрибут не найден
# обычным способом, поэтому константы выше переименованы с префиксом _RAW_.
#
# Так вызывающий код не меняется вовсе: он по-прежнему делает
# prompts.DIGEST_USER.format(...), но текст приходит из Langfuse, если тот
# доступен, и локальный — если нет.
def __getattr__(name: str) -> str:
    if not (name.isupper() and (name.endswith("_SYSTEM") or name.endswith("_USER"))):
        raise AttributeError(name)

    raw = globals().get(f"_RAW_{name}")
    if raw is None:
        raise AttributeError(name)

    try:
        from app.prompt_store import get_or

        return get_or(name, raw)
    except Exception:
        # prompt_store недоступен (циклический импорт при старте) — локальный
        return raw


