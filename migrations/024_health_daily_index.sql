-- Индекс под основной сценарий чтения метрик: «строки одного пользователя
-- за последние N дней» — так ходят вкладка «Здоровье», графики и советы.
-- Первичный ключ таблицы для этого не годится: у health_daily он свой,
-- а выборки всегда идут парой (user_id, day) с сортировкой по дню.
CREATE INDEX IF NOT EXISTS idx_health_daily_user_day
    ON health_daily (user_id, day DESC);
